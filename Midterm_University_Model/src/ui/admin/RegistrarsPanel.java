    public RegistrarsPanel(AppContext ctx, Session session) {
        this();
        session.requireRole(model.person.Role.Type.ADMIN);
        this.ctx = ctx;
        this.session = session;

        tblRegistrars.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
        // when a row is clicked, copy that registrar into the edit boxes
        tblRegistrars.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                fillForm();
            }
        });
        loadTable();

        // reload every time this page is shown, so the data is never old
        addComponentListener(new java.awt.event.ComponentAdapter() {
            @Override
            public void componentShown(java.awt.event.ComponentEvent e) {
                loadTable();
            }
        });
    }
        /** Fills the table with every registrar. */
    private void loadTable() {
        javax.swing.table.DefaultTableModel tableModel = new javax.swing.table.DefaultTableModel(
                new String[]{"University ID", "Name", "Email", "Phone", "Office hours", "Status"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;   // users cannot type in the table
            }
        };
        rowPersons.clear();
        for (model.person.Person p : ctx.getUniversity().getPersons(model.person.Role.Type.REGISTRAR)) {
            model.person.RegistrarRole registrar = p.getRole(model.person.RegistrarRole.class);
            tableModel.addRow(new Object[]{
                p.getUniversityId(),
                p.getFullName(),
                p.getEmail(),
                p.getPhone(),
                registrar == null ? "" : registrar.getOfficeHours(),
                p.isActive() ? "Active" : "Deactivated"});
            rowPersons.add(p);
        }
        tblRegistrars.setModel(tableModel);
        clearForm();
    }

    /** Copies the selected row into the edit boxes. */
    private void fillForm() {
        int row = tblRegistrars.getSelectedRow();
        if (row < 0) {
            return;
        }
        model.person.Person p = rowPersons.get(tblRegistrars.convertRowIndexToModel(row));
        model.person.RegistrarRole registrar = p.getRole(model.person.RegistrarRole.class);
        txtFirst.setText(p.getFirstName());
        txtLast.setText(p.getLastName());
        txtEmail.setText(p.getEmail());
        txtPhone.setText(p.getPhone());
        txtOffice.setText(registrar == null ? "" : registrar.getOfficeHours());
    }

    /** Empties the edit boxes. */
    private void clearForm() {
        txtFirst.setText("");
        txtLast.setText("");
        txtEmail.setText("");
        txtPhone.setText("");
        txtOffice.setText("");
    }
    private model.person.Person selectedPerson() {
        int row = tblRegistrars.getSelectedRow();
        if (row < 0) {
            throw new IllegalArgumentException("Select a registrar in the table first.");
        }
        return rowPersons.get(tblRegistrars.convertRowIndexToModel(row));
    }

