    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        // TODO add your handling code here:
       try {
        String type = (String) cmbType.getSelectedItem();
        String first = txtFirst.getText();
        String last = txtLast.getText();
        String email = txtEmail.getText();
        String phone = txtPhone.getText();
        int deptIndex = cmbDepartment.getSelectedIndex();
        int degreeIndex = cmbDegree.getSelectedIndex();
        model.person.Person created;

        if ("Student".equals(type)) {
            if (deptIndex < 0 || degreeIndex < 0) {
                throw new IllegalArgumentException("Choose a department and a degree program.");
            }
            created = ctx.getUniversity().registerStudent(first, last, email, phone,
                    departments.get(deptIndex), degrees.get(degreeIndex)).getPerson();
        } else if ("Faculty".equals(type)) {
            if (deptIndex < 0) {
                throw new IllegalArgumentException("Choose a department.");
            }
            created = ctx.getUniversity().registerFaculty(first, last, email, phone,
                    departments.get(deptIndex)).getPerson();
        } else {
            created = ctx.getUniversity().registerRegistrar(first, last, email, phone).getPerson();
        }

        javax.swing.JOptionPane.showMessageDialog(this,
                created.getFullName() + " registered with university ID " + created.getUniversityId()
                + ".\nGive this person a login on the Accounts page.");
        clearForm();
    } catch (IllegalArgumentException | IllegalStateException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(),
                "Cannot register", javax.swing.JOptionPane.ERROR_MESSAGE);
    } 
    }//GEN-LAST:event_btnRegisterActionPerformed

