    public RegisterPanel(AppContext ctx, Session session) {
        this();
        session.requireRole(model.person.Role.Type.ADMIN);
        this.ctx = ctx;
        this.session = session;
        
        loadDepartments();
        // when the department changes, show that department's degrees
        cmbDepartment.addActionListener(e -> loadDegrees());
        // department and degree matter only for some types
        cmbType.addActionListener(e -> updateEnabledFields());
        updateEnabledFields();
    }
    
        /** Fills the Department dropdown from the model. */
    private void loadDepartments() {
        departments = new java.util.ArrayList<>(ctx.getUniversity().getAllDepartments());
        cmbDepartment.removeAllItems();
        for (model.university.Department d : departments) {
            cmbDepartment.addItem(d.getName());
        }
        loadDegrees();
    }

    /** Fills the Degree dropdown for the selected department. */
    private void loadDegrees() {
        degrees = new java.util.ArrayList<>();
        cmbDegree.removeAllItems();
        int index = cmbDepartment.getSelectedIndex();
        if (index >= 0) {
            degrees = new java.util.ArrayList<>(departments.get(index).getDegrees());
            for (model.university.Degree degree : degrees) {
                cmbDegree.addItem(degree.getName());
            }
        }
    }

    /** Student needs department + degree. Faculty needs a department. Registrar needs neither. */
    private void updateEnabledFields() {
        String type = (String) cmbType.getSelectedItem();
        cmbDepartment.setEnabled(!"Registrar".equals(type));
        cmbDegree.setEnabled("Student".equals(type));
    }

