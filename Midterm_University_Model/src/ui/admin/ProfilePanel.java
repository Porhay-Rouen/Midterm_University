    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        try {
            model.person.Person me = session.getPerson();
            // check everything first, so a bad field cannot leave a half-saved profile
            model.util.Validation.requireText(txtFirst.getText(), "First name");
            model.util.Validation.requireText(txtLast.getText(), "Last name");
            model.util.Validation.optionalPhone(txtPhone.getText());
            ctx.getUniversity().changeEmail(me, txtEmail.getText());   // blocks a duplicate email
            me.setFirstName(txtFirst.getText());
            me.setLastName(txtLast.getText());
            me.setPhone(txtPhone.getText());
            loadProfile();
            javax.swing.JOptionPane.showMessageDialog(this, "Profile updated.");
        } catch (IllegalArgumentException | IllegalStateException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Cannot save profile", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

