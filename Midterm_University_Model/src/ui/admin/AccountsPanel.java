    /** Fills the table with every person and their login (if they have one). */
    private void loadTable() {
        javax.swing.table.DefaultTableModel tableModel = new javax.swing.table.DefaultTableModel(
                new String[]{"University ID", "Name", "Roles", "Username", "Status"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;   // users cannot type in the table
            }
        };
        rowPersons.clear();
        for (model.person.Person p : ctx.getUniversity().getPersons()) {
            String username = ctx.getAccessControl().usernameOf(p);
            tableModel.addRow(new Object[]{
                p.getUniversityId(),
                p.getFullName(),
                rolesText(p),
                username == null ? "(no account)" : username,
                p.isActive() ? "Active" : "Deactivated"});
            rowPersons.add(p);
        }
        tblPersons.setModel(tableModel);
    }

    /** "Student" or "Student, Faculty" text for a person's roles. */
    private String rolesText(model.person.Person p) {
        StringBuilder sb = new StringBuilder();
        for (model.person.Role r : p.getRoles()) {
            if (sb.length() > 0) {
                sb.append(", ");
            }
            sb.append(r.getRoleName());
        }
        return sb.toString();
    }
    /** The person in the selected table row. Throws a clear message if no row is selected. */
    private model.person.Person selectedPerson() {
        int row = tblPersons.getSelectedRow();
        if (row < 0) {
            throw new IllegalArgumentException("Select a person in the table first.");
        }
        return rowPersons.get(tblPersons.convertRowIndexToModel(row));
    }
