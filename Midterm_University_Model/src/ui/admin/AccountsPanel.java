    private void btnCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateActionPerformed
        // TODO add your handling code here:
        char[] password = txtPassword.getPassword();
        try {
            ctx.getAccessControl().createAccount(txtUsername.getText(), password, selectedPerson());
            txtUsername.setText("");
            txtPassword.setText("");
            loadTable();
            javax.swing.JOptionPane.showMessageDialog(this, "Account created.");
        } catch (IllegalArgumentException | IllegalStateException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Cannot create account", javax.swing.JOptionPane.ERROR_MESSAGE);
        } finally {
            java.util.Arrays.fill(password, '\0');   // wipe the password from memory
        }
    }//GEN-LAST:event_btnCreateActionPerformed

    private void btnResetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnResetActionPerformed
        // TODO add your handling code here:
        char[] password = txtPassword.getPassword();
        try {
            model.person.Person p = selectedPerson();
            String username = ctx.getAccessControl().usernameOf(p);
            if (username == null) {
                throw new IllegalStateException(p.getFullName() + " has no account yet.");
            }
            ctx.getAccessControl().resetPassword(username, password);
            txtPassword.setText("");
            javax.swing.JOptionPane.showMessageDialog(this, "Password updated for " + username + ".");
        } catch (IllegalArgumentException | IllegalStateException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Cannot reset password", javax.swing.JOptionPane.ERROR_MESSAGE);
        } finally {
            java.util.Arrays.fill(password, '\0');
        }
    }//GEN-LAST:event_btnResetActionPerformed

    private void btnToggleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnToggleActionPerformed
        // TODO add your handling code here:
        
        try {
            model.person.Person p = selectedPerson();
            if (p == session.getPerson()) {
                throw new IllegalStateException("You cannot deactivate your own account.");
            }
            p.setActive(!p.isActive());
            loadTable();
        } catch (IllegalArgumentException | IllegalStateException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Cannot change status", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    
    }//GEN-LAST:event_btnToggleActionPerformed

    private void btnToggle1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnToggle1ActionPerformed
        // TODO add your handling code here:
    try {
        model.person.Person p = selectedPerson();
        if (p == session.getPerson()) {
            throw new IllegalStateException("You cannot delete your own account.");
        }
        String username = ctx.getAccessControl().usernameOf(p);
        if (username == null) {
            throw new IllegalStateException(p.getFullName() + " has no account to delete.");
        }
        int answer = javax.swing.JOptionPane.showConfirmDialog(this,
                "Delete the login '" + username + "'? The person record stays.",
                "Please confirm", javax.swing.JOptionPane.YES_NO_OPTION);
        if (answer == javax.swing.JOptionPane.YES_OPTION) {
            ctx.getAccessControl().deleteAccount(username);
            loadTable();
        }
    } catch (IllegalArgumentException | IllegalStateException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(),
                "Cannot delete account", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnToggle1ActionPerformed

