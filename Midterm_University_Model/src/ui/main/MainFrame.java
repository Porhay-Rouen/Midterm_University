    private void buildMenu() {
        switch (session.getRoleType()) {
            case ADMIN:
                addPage("Dashboard", new ui.admin.DashboardPanel(ctx, session));
                break;
            case FACULTY:
                addPage("My Courses", new ui.faculty.MyCoursesPanel(ctx, session));
                break;
            case STUDENT:
                addPage("Student", new ui.student.StudentHomePanel(ctx, session));
                setSize(1100, 700);     // same window size as the Registrar screens
                setLocationRelativeTo(null);     // re-center after resizing
                break;               
            case REGISTRAR:
                addPage("Offerings", new ui.register.OfferingPanel(ctx, session));
                break;
        }
        addLogoutButton();
    }

    /** Adds the page to the CardLayout and makes a menu button that shows it. */
    private void addPage(String name, javax.swing.JPanel panel) {
        workArea.add(panel, name);
    ((java.awt.CardLayout) workArea.getLayout()).show(workArea, name);
    }

    private void addLogoutButton() {
        javax.swing.JButton logout = new javax.swing.JButton("Logout");
        logout.addActionListener(e -> {
            ctx.getAccessControl().logout(session);
            dispose();
            new ui.login.LoginFrame(ctx).setVisible(true);
        });
    }

