    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        // Lets the student pick a file for the selected assignment and records it as their submission
        SeatAssignment sa = selectedCourse();
        int row = tblAssignments.getSelectedRow();
        if (sa == null || row < 0) {
            JOptionPane.showMessageDialog(this, "Select an assignment in the table first.");
            return;
        }
        Assignment a = shown.get(row);

        JFileChooser chooser = new JFileChooser();          // the Mac's standard "Open" window
        chooser.setDialogTitle("Submit " + a.getTitle());
        if (chooser.showOpenDialog(this) != JFileChooser.APPROVE_OPTION) {
            return;   // they clicked Cancel: nothing submitted
        }
        String fileName = chooser.getSelectedFile().getName();
        try {
            sa.submit(a, fileName);
            loadAssignments();
            JOptionPane.showMessageDialog(this, "Submitted " + fileName + " for " + a.getTitle() + ".");
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Can't submit", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnSubmitActionPerformed

