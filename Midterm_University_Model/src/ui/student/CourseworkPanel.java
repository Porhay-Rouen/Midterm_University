    /**
     * Builds the Coursework page for the logged-in student.
     */
    public CourseworkPanel(AppContext ctx, Session session) {
        this();
        session.requireRole(Role.Type.STUDENT);
        this.ctx = ctx;
        this.session = session;
        student = (StudentRole) session.getRole();
        scrAssignments.getViewport().setBackground(Color.WHITE);  // white space under the rows
    }
    
    /**
     * Rebuilds the course list each time the page is shown (enrolling or
     * dropping changes it).
     */
    private void refresh() {
        loading = true;
        SeatAssignment previous = selectedCourse();
        cmbCourse.removeAllItems();
        myCourses.clear();
        for (SeatAssignment sa : student.getAllSeatAssignments()) {
            myCourses.add(sa);
            cmbCourse.addItem(sa.getSemester().getName() + " · " + sa.getCourse().getCourseId()
                    + " " + sa.getCourseOffering().getTitle());
        }
        int keep = myCourses.indexOf(previous);   // -1 if that course is gone (e.g., dropped)
        if (keep >= 0) {
            cmbCourse.setSelectedIndex(keep);
        }
        loading = false;
        loadAssignments();
    }

    /**
     * The student's SeatAssignment for the course picked in the dropdown (null
     * if none).
     */
    private SeatAssignment selectedCourse() {
        int i = cmbCourse.getSelectedIndex();
        if (i < 0 || i >= myCourses.size()) {
            return null;
        }
        return myCourses.get(i);
    }

    /**
     * Fills the table: the course's assignments, the student's submission, and
     * the score.
     */
    private void loadAssignments() {
        DefaultTableModel model = (DefaultTableModel) tblAssignments.getModel();
        model.setRowCount(0);
        shown.clear();
        SeatAssignment sa = selectedCourse();
        if (sa == null) {
            lblSummary.setText("You aren't enrolled in any courses yet.");
            btnSubmit.setEnabled(false);
            return;
        }
        for (Assignment a : sa.getCourseOffering().getAssignments()) {
            shown.add(a);
            String submitted = sa.getSubmission(a);   // null = not submitted yet
            Double score = sa.getScore(a);            // null = not graded yet
            model.addRow(new Object[]{
                a.getTitle(), // assignment title
                a.getMaxScore(), // max score
                submitted == null ? "—" : submitted,
                score == null ? "Not graded" : score
            });
        }
        if (shown.isEmpty()) {
            lblSummary.setText("No assignments posted yet for this course.");
            btnSubmit.setEnabled(false);
            return;
        }
        btnSubmit.setEnabled(true);
        String gradeSoFar = sa.hasScores() ? String.format("%.1f%%", sa.getPercentage()) : "—";
        lblSummary.setText("Grade so far: " + gradeSoFar
                + String.format(" · Submitted %.0f%% of assignments   ", sa.getSubmissionProgress()));
    }

