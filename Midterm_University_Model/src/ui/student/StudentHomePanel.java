    public StudentHomePanel(AppContext ctx, Session session) {
        this();
        session.requireRole(Role.Type.STUDENT);
        this.ctx = ctx;
        this.session = session;

        lblUser.setText("Signed in as " + session.getPerson().getFullName());

        // Stack the pages into the content area, each with a name tag
        pnlContent.add(new RegisterPanel(ctx, session), "Register");
        pnlContent.add(new PlaceholderPanel("Coursework"), "Coursework");
        pnlContent.add(new TranscriptPanel(ctx, session), "Transcript");
        pnlContent.add(new PlaceholderPanel("Grad. Audit"), "Grad. Audit");
        pnlContent.add(new TuitionPanel(ctx, session), "Tuition");
        pnlContent.add(new PlaceholderPanel("Profile"), "Profile");

        showPage("Register", btnRegister);
    }

    /**
     * Shows one page, updates the title, and highlights the active nav button.
     */
    private void showPage(String name, JButton activeButton) {
        ((CardLayout) pnlContent.getLayout()).show(pnlContent, name);
        lblTitle.setText("Student: " + name);
        for (Component c : pnlNav.getComponents()) {   // roll call: everything in the nav
            c.setBackground(INACTIVE);                  // everyone back to gray
        }
        activeButton.setBackground(ACTIVE);             // then the clicked one turns blue
    }

