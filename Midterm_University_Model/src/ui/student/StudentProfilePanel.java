    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // Saves the student's edits; checks every field first so a bad entry can't leave a half-saved profile
        try {
            Person me = session.getPerson();
            // 1. Check everything (each line throws an error with a message if the field is bad)
            Validation.requireText(txtFirst.getText(), "First name");
            Validation.requireText(txtLast.getText(), "Last name");
            Validation.optionalPhone(txtPhone.getText());
            // 2. Email last among the checks: the university blocks duplicates, then saves it
            ctx.getUniversity().changeEmail(me, txtEmail.getText());
            // 3. Everything passed, so save the rest
            me.setFirstName(txtFirst.getText());
            me.setLastName(txtLast.getText());
            me.setPhone(txtPhone.getText());
            loadProfile();
            JOptionPane.showMessageDialog(this, "Profile updated.");
        } catch (IllegalArgumentException | IllegalStateException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Can't save profile", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

