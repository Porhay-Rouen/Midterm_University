    /**
     * Builds the Student Profile page for the logged-in student.
     */
    public StudentProfilePanel(AppContext ctx, Session session) {
        this();
        session.requireRole(Role.Type.STUDENT);
        this.ctx = ctx;
        this.session = session;

        student = (StudentRole) session.getRole();
        // The Mac look draws text-box borders very faintly: give every box a clear gray outline
        // with a little padding inside, and shade the read-only boxes so they look locked.
        JTextField[] allBoxes = {txtId, txtFirst, txtLast, txtEmail, txtPhone, txtDepartment, txtDegree};
        for (JTextField box : allBoxes) {
            box.setBorder(BorderFactory.createCompoundBorder(
                    BorderFactory.createLineBorder(new Color(148, 163, 184)), // gray outline
                    BorderFactory.createEmptyBorder(3, 6, 3, 6))); // padding: top, left, bottom, right
        }
        JTextField[] readOnlyBoxes = {txtId, txtDepartment, txtDegree};
        for (JTextField box : readOnlyBoxes) {
            box.setBackground(new Color(241, 245, 249));   // light gray = can't edit
            box.setToolTipText("Set by the registrar; it can't be changed here.");
        }
    }

    /**
     * Copies the student's saved details into the boxes.
     */
    private void loadProfile() {
        Person me = session.getPerson();
        txtId.setText(me.getUniversityId());
        txtFirst.setText(me.getFirstName());
        txtLast.setText(me.getLastName());
        txtEmail.setText(me.getEmail());
        txtPhone.setText(me.getPhone());
        txtDepartment.setText(student.getDepartment().getName());
        txtDegree.setText(student.getDegree() == null ? "None assigned" : student.getDegree().getName());
    }

